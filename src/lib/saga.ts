/** Chapter N (1-based). After chapter 30 the story moves into "new missions" that replay the acts with harder fights. */
export function sagaChapter(n: number): { ch: Chapter; index: number; season: number } {
  const index = (n - 1) % SAGA.length;
  return { ch: SAGA[index]!, index, season: Math.floor((n - 1) / SAGA.length) + 1 };
}

const fill = (t: string, name: string, bond?: Bond) => tr(t).replaceAll("{name}", tr(name)).replaceAll("{ally}", bond ? tr(BONDS[bond].label) : tr("ميكاسا"));

/** Dialogue lines for a chapter, filtered by the player's earlier choices. */
export function sagaLines(n: number, st: SagaState, name: string) {
  const { ch, season } = sagaChapter(n);
  const picks = st.picks ?? {};
  const lines = ch.lines.filter((l) => {
    if (!l.when) return true;
    const [k, v] = l.when.split(":");
    return picks[k!] === Number(v);
  }).map((l) => ({ who: fill(l.who, name, st.bond), text: fill(l.text, name, st.bond) }));
  if (season > 1) lines.unshift({ who: tr("الراوي"), text: trf("مهمة جديدة (الدورة {season}): ذكريات «{title}» بترجع، والعدو بقى أقوى.", { season, title: ch.title }) });
  return lines;
}

export function sagaAsk(n: number, st: SagaState, name: string) {
  const { ch } = sagaChapter(n);
  return { ask: fill(ch.ask, name, st.bond), options: ch.options.map((o) => ({ label: fill(o.label, name, st.bond), reply: fill(o.reply, name, st.bond) })) };
}

/** Story choices: c1..c30 for the first run (later chapters remember them), s<N> for later cycles. */
export function pickKey(n: number) {
  const { index, season } = sagaChapter(n);
  return season === 1 ? `c${index + 1}` : `s${n}`;
}
export const hasPicked = (n: number, st: SagaState) => st.picks?.[pickKey(n)] !== undefined;
